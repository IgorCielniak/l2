#!/usr/bin/env python3
"""Compile-time performance benchmark for the CT API refactor.

Times the Python compiler front end and code generation (`--emit-asm
--no-cache --no-daemon`) over a fixed benchmark set, so NASM/ld time and
cache hits do not affect the result. Each file is compiled several times and
the median wall-clock time is reported.

Usage:
    python3 tools/bench_compile.py                   # run, print table
    python3 tools/bench_compile.py --runs 7 --json out.json
    python3 tools/bench_compile.py --compare base.json   # show change vs. baseline
    python3 tools/bench_compile.py --generate        # (re)write the large file
    python3 tools/bench_compile.py --ab ../base-tree --runs 9 \
        --max-file-regression 5 --max-geomean 0      # interleaved A/B gate

`--ab TREE` times TREE (for example a `git worktree` of a base commit) and
this tree alternately, file by file, so machine-speed drift during the run
affects both sides equally; compare-across-sessions numbers on a laptop can
differ by several times.  `--max-file-regression` and `--max-geomean` make
the run exit with status 1 when any single file, or the geometric mean of
the per-file changes, is slower than the given percentage.

The benchmark set is fixed; do not edit it, so results stay comparable with
earlier runs.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
LARGE = Path("tools/bench/large_generated.sl")

BENCH_FILES = [
    "examples/eval_runtime.sl",
    "examples/game_of_life.sl",
    "examples/hma_test.sl",
    "examples/snake.sl",
    "examples/time_accuracy.sl",
    "extra_tests/fn_dsl_test.sl",
    "tests/integration_core.sl",
    LARGE.as_posix(),
]


def generate_large(words: int = 1500) -> str:
    """Deterministic large source using only refactor-stable constructs."""
    out = [
        "# Generated by tools/bench_compile.py --generate. Do not edit by hand.",
        "# Uses only constructs whose names and syntax the CT API refactor keeps.",
        "import stdlib/stdlib.sl",
        "import stdlib/io.sl",
        "",
        "word bench_ct_table",
        "    list-new",
    ]
    for i in range(64):
        out.append(f"    {i * 7 % 101} list-append")
    out += [
        "    list-length drop",
        "    map-new 1 2 map-set 3 4 map-set map-length drop",
        "end",
        "compile-time bench_ct_table",
        "",
    ]
    for i in range(words):
        a, b, c = i % 13 + 1, i % 7 + 2, i % 5
        out.append(f"word bench_w{i}")
        out.append(f"    {a} {b} + dup {c} > if")
        out.append(f"        {b} * {i % 9} -")
        out.append("    else")
        out.append(f"        {a} swap -")
        out.append("    end")
        if i % 3 == 0:
            out.append(f"    0 {i % 4 + 2} for 1 + end")
        if i % 4 == 0:
            out.append("    0 while dup 3 < do 1 + end drop")
        if i % 5 == 0 and i > 0:
            out.append(f"    bench_w{i - 1} +")
        out.append("end")
        out.append("")
    out += ["word main"]
    for i in range(0, words, max(1, words // 50)):
        out.append(f"    bench_w{i} drop")
    out += ['    "bench done" puts cr', "    0", "end", ""]
    return "\n".join(out)


def compile_once(path: str, out_dir: Path, tree: Path = ROOT) -> float:
    target = out_dir / (Path(path).stem + ".asm")
    cmd = [sys.executable, "main.py", path, "--emit-asm", "--no-cache",
           "--no-daemon", "-o", str(target)]
    started = time.perf_counter()
    proc = subprocess.run(cmd, cwd=tree, capture_output=True, text=True, stdin=subprocess.DEVNULL)
    elapsed = time.perf_counter() - started
    if proc.returncode != 0:
        raise RuntimeError(f"compile failed for {path}:\n{proc.stdout}{proc.stderr}")
    return elapsed


def git_head() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True).stdout.strip()
    except OSError:
        return "unknown"


def run(runs: int) -> dict:
    results: Dict[str, dict] = {}
    with tempfile.TemporaryDirectory() as tmp:
        out_dir = Path(tmp)
        for path in BENCH_FILES:
            compile_once(path, out_dir)  # warm-up (OS caches, imports)
            times = [compile_once(path, out_dir) for _ in range(runs)]
            results[path] = {"median": statistics.median(times),
                             "min": min(times), "max": max(times)}
            print(f"  {path:<34} median {results[path]['median']:.3f}s", flush=True)
    total = sum(r["median"] for r in results.values())
    return {
        "commit": git_head(),
        "python": platform.python_version(),
        "machine": f"{platform.system()} {platform.machine()} {platform.processor() or ''}".strip(),
        "runs": runs,
        "files": results,
        "total_median": total,
    }


def run_ab(base_tree: Path, runs: int) -> tuple:
    """Interleaved A/B: every round times each file in both trees, in an
    order that alternates between rounds.  Returns (base, current) results
    shaped like run()'s."""
    trees = (base_tree.resolve(), ROOT)
    times: Dict[Path, Dict[str, List[float]]] = {tree: {path: [] for path in BENCH_FILES} for tree in trees}
    with tempfile.TemporaryDirectory() as tmp:
        out_dir = Path(tmp)
        for path in BENCH_FILES:  # warm-up
            for tree in trees:
                compile_once(path, out_dir, tree)
        for round_index in range(runs):
            for path in BENCH_FILES:
                for tree in (trees if round_index % 2 == 0 else trees[::-1]):
                    times[tree][path].append(compile_once(path, out_dir, tree))
            print(f"  round {round_index + 1}/{runs} done", flush=True)

    def shaped(tree: Path) -> dict:
        files = {path: {"median": statistics.median(values), "min": min(values), "max": max(values)}
                 for path, values in times[tree].items()}
        return {"commit": tree.name, "python": platform.python_version(), "runs": runs, "files": files,
                "total_median": sum(item["median"] for item in files.values())}

    return shaped(trees[0]), shaped(trees[1])


def compare(current: dict, base: dict, *, max_file: Optional[float] = None,
            max_geomean: Optional[float] = None) -> bool:
    """Print the comparison; False when a given threshold is exceeded."""
    ok = True
    print(f"\n{'file':<34} {'base':>8} {'now':>8} {'change':>8}")
    for path, now in current["files"].items():
        old = base["files"].get(path)
        if not old:
            print(f"{path:<34} {'-':>8} {now['median']:8.3f} {'new':>8}")
            continue
        delta = (now["median"] / old["median"] - 1) * 100
        flag = ""
        if max_file is not None and delta > max_file:
            flag = f"  OVER the {max_file:+.1f}% per-file limit"
            ok = False
        print(f"{path:<34} {old['median']:8.3f} {now['median']:8.3f} {delta:+7.1f}%{flag}")
    total_delta = (current["total_median"] / base["total_median"] - 1) * 100
    print(f"{'TOTAL':<34} {base['total_median']:8.3f} {current['total_median']:8.3f} {total_delta:+7.1f}%")
    ratios = [now["median"] / base["files"][path]["median"]
              for path, now in current["files"].items() if path in base["files"]]
    geo = (statistics.geometric_mean(ratios) - 1) * 100 if ratios else 0.0
    budget = 20.0
    status = "within" if geo <= budget else "OVER"
    print(f"Budget metric (geometric mean of per-file changes): {geo:+.1f}% — "
          f"{status} the {budget:.0f}% global budget")
    if max_geomean is not None and geo > max_geomean:
        print(f"Geometric mean OVER the {max_geomean:+.1f}% limit")
        ok = False
    return ok


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs", type=int, default=5, help="timed runs per file (default 5)")
    ap.add_argument("--json", metavar="PATH", help="write results as JSON")
    ap.add_argument("--compare", metavar="PATH", help="baseline JSON to compare against")
    ap.add_argument("--generate", action="store_true", help="write the large generated file and exit")
    ap.add_argument("--ab", metavar="TREE", help="interleaved A/B against another checkout (base) of the repo")
    ap.add_argument("--max-file-regression", type=float, metavar="PCT",
                    help="exit 1 if any file is more than PCT%% slower than the base")
    ap.add_argument("--max-geomean", type=float, metavar="PCT",
                    help="exit 1 if the geometric mean change exceeds PCT%%")
    args = ap.parse_args(argv)
    limits = {"max_file": args.max_file_regression, "max_geomean": args.max_geomean}

    if args.generate:
        target = ROOT / LARGE
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generate_large(), encoding="utf-8")
        print(f"wrote {LARGE}")
        return 0

    if args.ab:
        print(f"Interleaved A/B, base {args.ab} vs this tree, {len(BENCH_FILES)} files, {args.runs} rounds:")
        base, data = run_ab(Path(args.ab), args.runs)
        if args.json:
            Path(args.json).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        return 0 if compare(data, base, **limits) else 1

    print(f"Benchmarking {len(BENCH_FILES)} files, {args.runs} runs each (median):")
    data = run(args.runs)
    print(f"Total of medians: {data['total_median']:.3f}s "
          f"(Python {data['python']}, {data['machine']}, commit {data['commit']})")
    if args.json:
        Path(args.json).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    if args.compare:
        if not compare(data, json.loads(Path(args.compare).read_text(encoding="utf-8")), **limits):
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
