#!/usr/bin/env python3
"""Generate stdlib/linux.sl from syscall_64.tbl metadata."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "syscall_64.tbl"
DST = ROOT / "stdlib" / "linux.sl"


def _sanitize_alias(alias: str) -> str:
    name = alias.strip()
    if not name:
        return ""
    if name.startswith("__x64_sys_"):
        name = name[len("__x64_sys_") :]
    elif name.startswith("sys_"):
        name = name[len("sys_") :]
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    if not name:
        return ""
    if name[0].isdigit():
        name = "n_" + name
    return name


@dataclass(frozen=True)
class SyscallEntry:
    argc: int
    num: int
    aliases: tuple[str, ...]


def _parse_table(path: Path) -> list[SyscallEntry]:
    entries: list[SyscallEntry] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(maxsplit=2)
        if len(parts) < 3:
            continue
        try:
            argc = int(parts[0])
            num = int(parts[1])
        except ValueError:
            continue
        aliases = tuple(a for a in parts[2].split("/") if a)
        if not aliases:
            continue
        entries.append(SyscallEntry(argc=argc, num=num, aliases=aliases))
    return entries


# Everything before the per-syscall entries, verbatim.
_HEADER = '# Autogenerated from syscall_64.tbl\n# Generated by tools/gen_linux_sl.py\n# Linux syscall constants + convenience wrappers for L2\n\n# File descriptor constants\nconst FD_STDIN 0\nconst FD_STDOUT 1\nconst FD_STDERR 2\n\n# Common open(2) flags\nconst O_RDONLY 0\nconst O_WRONLY 1\nconst O_RDWR 2\nconst O_CREAT 64\nconst O_EXCL 128\nconst O_NOCTTY 256\nconst O_TRUNC 512\nconst O_APPEND 1024\nconst O_NONBLOCK 2048\nconst O_CLOEXEC 524288\n\n# lseek(2)\nconst SEEK_SET 0\nconst SEEK_CUR 1\nconst SEEK_END 2\n\n# mmap(2)\nconst PROT_NONE 0\nconst PROT_READ 1\nconst PROT_WRITE 2\nconst PROT_EXEC 4\nconst MAP_PRIVATE 2\nconst MAP_ANONYMOUS 32\nconst MAP_SHARED 1\n\n# Socket constants\nconst AF_UNIX 1\nconst AF_INET 2\nconst AF_INET6 10\nconst SOCK_STREAM 1\nconst SOCK_DGRAM 2\nconst SOCK_NONBLOCK 2048\nconst SOCK_CLOEXEC 524288\nconst INADDR_ANY 0\n\n# Generic syscall helpers with explicit argument count\n# Stack form:\n#   syscall  -> <argN> ... <arg0> <argc> <nr> syscall\n#   syscallN -> <argN-1> ... <arg0> <nr> syscallN\n\n# swap impl is provided so this can be used without stdlib\n# ___linux_swap [*, x1 | x2] -> [*, x2 | x1]\n:asm ___linux_swap {\n    mov rax, [r12]\n    mov rbx, [r12 + 8]\n    mov [r12], rbx\n    mov [r12 + 8], rax\n}\n;\n\nmacro syscall0 `\n    0\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall1 `\n    1\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall2 `\n    2\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall3 `\n    3\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall4 `\n    4\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall5 `\n    5\n    ___linux_swap\n    syscall\n` emit ;\n\nmacro syscall6 `\n    6\n    ___linux_swap\n    syscall\n` emit ;\n\n'


def _emit_header(lines: list[str]) -> None:
    lines.extend(_HEADER.split("\n")[:-1])


def _emit_entry(lines: list[str], alias: str, argc: int, num: int) -> None:
    safe_argc = max(0, min(argc, 6))
    lines.extend(
        [
            f"macro syscall.{alias} `",
            f"    {num}",
            f"    syscall{safe_argc}",
            "` emit ;",
            "",
            f"const syscall.{alias}.num {num}",
            f"const syscall.{alias}.argc {safe_argc}",
            "",
        ]
    )


def generate() -> str:
    entries = _parse_table(SRC)

    lines: list[str] = []
    _emit_header(lines)

    emitted: set[str] = set()
    for entry in sorted(entries, key=lambda e: (e.num, e.aliases[0])):
        for alias in entry.aliases:
            name = _sanitize_alias(alias)
            if not name:
                continue
            key = f"syscall.{name}"
            if key in emitted:
                continue
            _emit_entry(lines, name, entry.argc, entry.num)
            emitted.add(key)

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    output = generate()
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(output, encoding="utf-8")
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()
